class ScoreSettlementTests(unittest.TestCase):
    """Score semantics; these are the H-01 regression tests (fail on the old code)."""

    def test_reach_hora_deltas_already_include_kyotaku(self):
        # delta sum is +1000 == 1 kyotaku; the old code added another +1000.
        self.assertEqual(
            replay.final_scores_from_events(CARRY_HORA_EVENTS),
            [22900, 31300, 22900, 22900],
        )

    def test_kyotaku_carries_through_ryukyoku_to_next_kyoku(self):
        result = replay.replay_scores(CARRY_HORA_CHAIN)
        self.assertTrue(result.ok, result.errors)
        self.assertEqual(result.protocol, replay.PROTOCOL_TENHOU_DELTAS)
        self.assertEqual(result.kyoku_count, 3)
        self.assertEqual(len(result.transitions), 2)
        for transition in result.transitions:
            self.assertTrue(transition["match"], transition)
        # E2 honba 0 ryukyoku leaves one stick; the next kyoku starts with 1.
        self.assertEqual(result.transitions[0]["settled_kyotaku"], 1)
        self.assertEqual(result.transitions[0]["next_kyotaku"], 1)
        self.assertEqual(result.kyotaku_left, 0)
        self.assertEqual(result.final_kyotaku_award_seat, None)
        self.assertEqual(sum(result.scores), 100000)

    def test_double_ron_kyotaku_paid_to_first_winner_only(self):
        # End before the next start_kyoku so the legacy entry point must settle it.
        self.assertEqual(
            replay.final_scores_from_events(DOUBLE_RON_EVENTS),
            [19800, 29900, 25300, 25000],
        )

    def test_double_ron_transition_and_second_delta_sum(self):
        result = replay.replay_scores(DOUBLE_RON_CHAIN)
        self.assertTrue(result.ok, result.errors)
        self.assertEqual(result.hora_count, 2)
        self.assertEqual(result.multi_ron_count, 1)
        self.assertEqual(result.kyotaku_left, 0)
        self.assertEqual(len(result.transitions), 1)
        self.assertTrue(result.transitions[0]["match"], result.transitions[0])
        hora_sums = [h["delta_sum"] for h in result.hora_records]
        self.assertEqual(hora_sums, [2000, 0])
        self.assertEqual(sum(result.scores), 100000)

    def test_four_riichi_abort_charges_pending_reach(self):
        # The fourth riichi has no reach_accepted but is still deducted (synthetic shape).
        result = replay.replay_scores(FOUR_RIICHI_EVENTS)
        self.assertTrue(result.ok, result.errors)
        self.assertEqual(result.scores, [24000, 24000, 24000, 24000])
        self.assertEqual(result.kyotaku_left, 4)
        self.assertIn("four_riichi_pending_reach_charged", result.flags)
        # And the next start_kyoku agrees with the settled scores/kyotaku.
        chained = replay.replay_scores(FOUR_RIICHI_EVENTS + [FOUR_RIICHI_NEXT])
        self.assertTrue(chained.ok, chained.errors)
        self.assertTrue(chained.transitions[0]["match"], chained.transitions[0])

    def test_four_riichi_legacy_final_scores(self):
        self.assertEqual(
            replay.final_scores_from_events(FOUR_RIICHI_EVENTS),
            [24000, 24000, 24000, 24000],
        )

    def test_last_kyoku_leftover_kyotaku_matches_native_anchor(self):
        # Legacy entry point must include the native end-of-game allocation too.
        self.assertEqual(
            replay.final_scores_from_events(NATIVE_LEFTOVER_EVENTS),
            NATIVE_LEFTOVER_FINAL,
        )
        result = replay.replay_scores(NATIVE_LEFTOVER_EVENTS)
        self.assertTrue(result.ok, result.errors)
        self.assertEqual(result.scores, NATIVE_LEFTOVER_FINAL)
        self.assertEqual(result.scores_before_final_kyotaku,
                         [25000, 25000, 24000, 25000])
        self.assertEqual(result.kyotaku_left, 1)
        self.assertEqual(result.final_kyotaku_award_seat, 0)
        self.assertIn("final_kyotaku_awarded", result.flags)
        self.assertEqual(sum(result.scores), 100000)

    def test_absolute_scores_protocol_fails_closed(self):
        with self.assertRaises(replay.ScoreProtocolError):
            replay.replay_scores(TENHOU_ABSOLUTE_EVENTS)
        # The lenient compatibility entry point must also refuse to invent scores.
        self.assertIsNone(replay.final_scores_from_events(TENHOU_ABSOLUTE_EVENTS))

    def test_inconsistent_hora_deltas_fail_closed(self):
        # Old fixture: deltas sum -1000 while one kyotaku (1000) is live -> unverified.
        bad = [
            START_GAME,
            {"type": "start_kyoku", "scores": [25000] * 4, "kyotaku": 0},
            {"type": "reach_accepted", "actor": 0},
            {"type": "hora", "actor": 0, "target": 0, "deltas": [-1000, 0, 0, 0]},
            {"type": "end_game"},
        ]
        result = replay.replay_scores(bad, strict_protocol=False)
        self.assertFalse(result.ok)
        self.assertTrue(any(m["kind"] == "hora_delta_sum_mismatch"
                            for m in result.mismatches), result.mismatches)
        self.assertIsNone(replay.final_scores_from_events(bad))

    def test_kyoku_count_uses_raw_boundaries(self):
        events = [
            START_GAME,
            {"type": "start_kyoku", "bakaze": "E", "kyoku": 1, "honba": 0,
             "kyotaku": 0, "scores": [25000] * 4},
            # abortive draw with zero decisions, restarted as honba 1 of the same kyoku
            {"type": "ryukyoku", "deltas": [0, 0, 0, 0]},
            {"type": "end_kyoku"},
            {"type": "start_kyoku", "bakaze": "E", "kyoku": 1, "honba": 1,
             "kyotaku": 0, "scores": [25000] * 4},
            {"type": "reach_accepted", "actor": 0},
            {"type": "ryukyoku", "deltas": [-1500, 1500, 1500, -1500]},
            {"type": "end_kyoku"},
            {"type": "start_kyoku", "bakaze": "E", "kyoku": 2, "honba": 0,
             "kyotaku": 1, "scores": [22500, 26500, 26500, 23500]},
            {"type": "ryukyoku", "deltas": [0, 0, 0, 0]},
            {"type": "end_kyoku"},
            {"type": "end_game"},
        ]
        result = replay.replay_scores(events)
        self.assertTrue(result.ok, result.errors)
        self.assertEqual(result.kyoku_count, 3)
        self.assertEqual(result.kyotaku_left, 1)
        # One leftover stick is awarded at end_game; totals stay at 100000.
        self.assertEqual(sum(result.scores), 100000)

    def test_transition_mismatch_is_reported(self):
        events = [
            START_GAME,
            {"type": "start_kyoku", "scores": [25000] * 4, "kyotaku": 0},
            {"type": "hora", "actor": 0, "target": 1, "deltas": [-1000, 1000, 0, 0]},
            {"type": "end_kyoku"},
            # deliberately wrong anchor: the real log would say [24000, 26000, 25000, 25000]
            {"type": "start_kyoku", "scores": [24500, 25500, 25000, 25000], "kyotaku": 0},
            {"type": "ryukyoku", "deltas": [0, 0, 0, 0]},
            {"type": "end_kyoku"},
            {"type": "end_game"},
        ]
        result = replay.replay_scores(events)
        self.assertFalse(result.ok)
        self.assertEqual(result.mismatches[0]["kind"], "kyoku_transition")
        self.assertEqual(result.mismatches[0]["settled_scores"],
                         [24000, 26000, 25000, 25000])

    def test_no_start_kyoku_returns_none(self):
        self.assertIsNone(replay.final_scores_from_events([{"type": "start_game"}]))


@unittest.skipUnless(have_libriichi(), "libriichi is not importable")
class ReplayIntegrationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.path = first_dataset_log()
        if cls.path is None:
            raise unittest.SkipTest("no local dataset log")
        cls.text = read_text(cls.path)

    def test_real_game_replays_and_all_actions_are_legal(self):
        result = replay.replay_game(self.text, oracle=False)
        self.assertTrue(result.ok, result.error)
        self.assertEqual(len(result.seats), 4)
        self.assertGreater(sum(seat["decisions"] for seat in result.seats), 0)
        for seat in result.seats:
            self.assertEqual(seat["invalid_actions"], [])
            self.assertGreater(seat["min_legal_count"], 0)
        self.assertIsNotNone(result.final_scores)
        self.assertEqual(len(result.final_scores), 4)
        self.assertEqual(sum(result.final_scores), 100000)

    def test_masks_are_46_wide(self):
        result = replay.replay_game(self.text, oracle=False, include_masks=True)
        self.assertTrue(result.ok, result.error)
        self.assertEqual(len(result.masks), 4)
        for seat_masks in result.masks:
            for mask in seat_masks:
                self.assertEqual(len(mask), replay.ACTION_SPACE)

    def test_bad_json_returns_error_not_exception(self):
        result = replay.replay_game("{not json}\n")
        self.assertFalse(result.ok)
        self.assertEqual(result.error_kind, "bad_json")

    def test_zero_seat_rejected(self):
        """A loader that returns 0 seats must not be accepted as a valid game."""
        class EmptyLoader:
            def __init__(self, *args, **kwargs):
                pass

            def load_log(self, raw_log):
                return []

        fake = types.SimpleNamespace(
            dataset=types.SimpleNamespace(GameplayLoader=EmptyLoader)
        )
        with mock.patch.object(replay, "load_libriichi", return_value=fake):
            result = replay.replay_game(
                '{"type":"start_game","names":["a","b","c","d"]}\n'
            )
        self.assertFalse(result.ok)
        self.assertEqual(result.error_kind, "seat_count")
        self.assertIn("got 0", result.error)

    def test_kyoku_count_matches_raw_boundaries_not_seat0(self):
        """Real log where seat 0 skipped one kyoku (abortive draw after zero actions)."""
        path = None
        directory = dataset_year_dir()
        if directory is not None:
            candidate = directory / "2025061404gm-00a9-0000-c5b3fa50.mjson"
            if candidate.is_file():
                path = candidate
        if path is None:
            self.skipTest("boundary fixture log not present")
        text = read_text(path)
        result = replay.replay_game(text, oracle=False)
        raw_count = sum(1 for line in text.splitlines()
                        if line.strip() and json.loads(line).get("type") == "start_kyoku")
        self.assertTrue(result.ok, result.error)
        self.assertEqual(result.kyoku_count, 12)
        self.assertEqual(result.kyoku_count, raw_count)
        self.assertEqual(result.native_kyoku_count, 12)
        self.assertEqual(result.seat0_kyoku_count, 11)
        self.assertTrue(result.kyoku_cross_check["match"], result.kyoku_cross_check)
        self.assertIn("seat0_kyoku_undercount", result.score_flags)


class RealCorpusCrossCheckTests(unittest.TestCase):
    """H-01 required cross-check: 200+ real games with riichi/kyotaku."""

    def test_200_games_with_kyotaku_transitions_match(self):
        directory = dataset_year_dir("2025")
        if directory is None:
            self.skipTest("no local 2025 dataset")
        files = sorted(directory.glob("*.mjson"))
        if len(files) < 400:
            self.skipTest("short local corpus")
        checked = 0
        transitions = 0
        hora_with_kyotaku = 0
        leftovers = 0
        failures = []
        for path in files[:400]:
            events = load_events(path)
            has_kyotaku = any(int(e.get("kyotaku", 0) or 0) > 0
                              for e in events if e.get("type") == "start_kyoku")
            if not has_kyotaku:
                continue
            try:
                result = replay.replay_scores(events)
            except replay.ScoreProtocolError as exc:  # pragma: no cover - evidence
                failures.append((path.name, f"protocol: {exc}"))
                continue
            checked += 1
            transitions += len(result.transitions)
            hora_with_kyotaku += sum(
                1 for record in result.hora_records if record["kyotaku_before"] > 0
            )
            leftovers += 1 if result.kyotaku_left > 0 else 0
            if not result.ok:
                failures.append((path.name, result.mismatches or result.errors))
            if result.scores is None or sum(result.scores) != 100000:
                failures.append((path.name, f"score sum {result.scores}"))
        self.assertGreaterEqual(checked, 200, f"only {checked} kyotaku games checked")
        self.assertEqual(failures, [], failures[:5])
        # Keep the observed volumes visible in the test log for the audit.
        print(f"\n[real-corpus] games={checked} transitions={transitions} "
              f"hora_with_kyotaku={hora_with_kyotaku} games_with_leftover={leftovers}")


