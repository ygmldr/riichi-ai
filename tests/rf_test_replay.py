from riichiformer.data import replay  # noqa: E402


def have_libriichi() -> bool:
    try:
        import libriichi  # noqa: F401
        return True
    except Exception:  # noqa: BLE001
        return False


def dataset_roots() -> list[Path]:
    """Candidate read-only dataset roots (env override, repo, sibling worktree root)."""
    roots = []
    env = os.environ.get("RF_DATASETS_ROOT")
    if env:
        roots.append(Path(env))
    roots.append(REPO_ROOT / "datasets")
    roots.append(REPO_ROOT.parent.parent / "datasets")
    return roots


def dataset_year_dir(year: str = "2025") -> Path | None:
    for root in dataset_roots():
        directory = root / "extracted" / year
        if directory.is_dir():
            return directory
    return None


def first_dataset_log():
    directory = dataset_year_dir()
    if directory is None:
        return None
    for year in ("2026", "2025", "2024", "2023"):
        candidate = directory.parent / year
        if not candidate.is_dir():
            continue
        files = sorted(candidate.glob("*.mjson"))
        if files:
            return files[0]
    return None


def read_text(path: Path) -> str:
    raw = path.read_bytes()
    return (gzip.decompress(raw) if raw.startswith(b"\x1f\x8b") else raw).decode("utf-8")


def load_events(path: Path) -> list[dict]:
    return [json.loads(line) for line in read_text(path).splitlines() if line.strip()]


