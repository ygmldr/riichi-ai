#!/usr/bin/env python3
"""Tests for the RiichiFormer replay/score adapter (PR-04 + H-01).

Score fixtures are **synthetic** event sequences that encode the arithmetic shapes
observed in the local corpus; no verbatim Tenhou log text, player name, account id or
log URL is embedded here:

* ``CARRY_HORA_EVENTS``: reach + ryukyoku leaves one stick, then a later hora whose
  ``deltas`` already include that 1000 points.
* ``DOUBLE_RON_EVENTS``: two live sticks; the first winner's deltas include both,
  the second winner's deltas contain no kyotaku.
* ``FOUR_RIICHI_EVENTS``: three accepted reaches plus a pending fourth reach and an
  all-zero abortive ryukyoku (the fourth stick is still paid).
* ``NATIVE_LEFTOVER_EVENTS``: the last kyoku of a log generated by the pinned native
  arena for a fixed seed; its ``end_game`` anchor is ``[26000, 25000, 24000, 25000]``.
* ``TENHOU_ABSOLUTE_EVENTS``: a synthetic absolute-scores ``hora`` protocol that is
  intentionally rejected.

The real-corpus tests read local datasets at runtime (never copied into the repo) and
are skipped when libriichi/datasets are unavailable.
"""

